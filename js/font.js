  // Псевдонимы для одинаковых по начертанию букв
  function resolve(ch, depth) {
    const g = G[ch];
    if (typeof g === 'string' && (depth || 0) < 5) return resolve(g, (depth || 0) + 1);
    return g || null;
  }

  function arcPoints(cx, cy, rx, ry, a0, a1) {
    const pts = [];
    const span = a1 - a0;
    const n = Math.max(2, Math.ceil(Math.abs(span) / 10));
    for (let i = 0; i <= n; i++) {
      const a = (a0 + (span * i) / n) * Math.PI / 180;
      pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
    }
    return pts;
  }

  function parseStrokes(src) {
    if (!src) return [];
    return src.split('|').map(s => {
      const pts = [];
      for (const tok of s.trim().split(/\s+/)) {
        if (!tok) continue;
        if (tok[0] === '@') {
          const [cx, cy, rx, ry, a0, a1] = tok.slice(1).split(',').map(Number);
          for (const p of arcPoints(cx, cy, rx, ry, a0, a1)) pts.push(p);
        } else {
          const [x, y] = tok.split(',').map(Number);
          pts.push([x, y]);
        }
      }
      return pts;
    }).filter(p => p.length > 0);
  }

  const cache = new Map();

  /** Возвращает {w, strokes, asc, desc} или null если символа нет */
  // Загруженный пользователем шрифт (см. customfont.js): для текста, а по желанию и для формул
  let custom = null, customMath = false;
  // mathMode: 'none' — формулы встроенным шрифтом; 'digits' — в формулах цифры из шрифта; 'all' — формулы целиком шрифтом
  let mathMode = 'digits';
  function setCustom(font, mode) { custom = font || null; mathMode = mode === true ? 'all' : mode === false ? 'none' : (mode || 'digits'); customMath = mathMode === 'all'; }

  // Второй шрифт вперемешку и «небрежность»: буквы не выходят одинаковыми копиями.
  // Случайность детерминированная: номер буквы в вёрстке + зерно → один и тот же текст выглядит одинаково.
  let mixFont = null, mixRatio = 0, jitter = 0, seed = 1, counter = 0;
  function setMix(font, ratio, jit) { mixFont = font || null; mixRatio = Math.max(0, Math.min(1, +ratio || 0)); jitter = Math.max(0, Math.min(1, +jit || 0)); }
  function beginLayout(sd) { seed = (sd >>> 0) || 1; counter = 0; }
  function rnd(n, k) { // псевдослучайное 0..1 по номеру буквы
    let t = (seed ^ Math.imul(n + 1, 0x9E3779B1) ^ Math.imul(k + 7, 0x85EBCA77)) >>> 0;
    t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  /** Небольшая неровность буквы: размер, наклон, поворот, сдвиг по высоте */
  function wobble(g, n) {
    if (!jitter || !g || !g.strokes.length) return g;
    const j = jitter;
    const sc = 1 + (rnd(n, 1) - 0.5) * 0.36 * j;              // размер ±18 %
    const sx = sc * (1 + (rnd(n, 5) - 0.5) * 0.16 * j);       // ширина ещё ±8 %
    const rot = (rnd(n, 2) - 0.5) * 20 * j * Math.PI / 180;   // поворот ±10°
    const sh = (rnd(n, 3) - 0.5) * 0.5 * j;                   // наклон ±0.25
    const dy = (rnd(n, 4) - 0.5) * 3.2 * j;                   // прыгает по высоте ±1.6 (≈0,7 мм при букве 4 мм)
    const dx = (rnd(n, 6) - 0.5) * 1.0 * j;
    // дрожание линий: плавная волна по точкам буквы
    const amp = 0.45 * j, f1 = 0.9 + rnd(n, 7) * 1.2, f2 = 0.9 + rnd(n, 8) * 1.2, p1 = rnd(n, 9) * 6.28, p2 = rnd(n, 10) * 6.28;
    const cx = g.w / 2, c = Math.cos(rot), si = Math.sin(rot);
    let asc = 0, desc = 0;
    const strokes = g.strokes.map(st => st.map(([x, y]) => {
      if (x !== x) return [x, y];                               // служебная метка (NaN) — не трогаем
      const wx = x + amp * Math.sin(y * f1 + p1), wy = y + amp * Math.sin(x * f2 + p2);
      let X = (wx - cx) * sx, Y = wy * sc;
      X += Y * sh;
      const xr = X * c - Y * si + cx + dx, yr = X * si + Y * c + dy;
      if (yr > asc) asc = yr; if (-yr > desc) desc = -yr;
      return [xr, yr];
    }));
    return { w: g.w * sx, strokes, asc: Math.max(asc, g.asc * sc), desc: Math.max(desc, g.desc * sc) };
  }

